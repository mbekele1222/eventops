BEGIN;

CREATE TABLE registrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL,
    full_name VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL,
    status VARCHAR(20) NOT NULL,
    cancellation_token_hash VARCHAR(64) NOT NULL UNIQUE,
    checked_in BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT registrations_event_fk
        FOREIGN KEY (event_id)
        REFERENCES events(id)
        ON DELETE RESTRICT,

    CONSTRAINT registrations_name_not_blank
        CHECK (length(trim(full_name)) > 0),

    CONSTRAINT registrations_email_normalized
        CHECK (
            email = lower(trim(email))
            AND length(email) > 0
        ),

    CONSTRAINT registrations_status_valid
        CHECK (status IN ('CONFIRMED', 'WAITLISTED', 'CANCELLED')),

    CONSTRAINT registrations_token_hash_length
        CHECK (length(cancellation_token_hash) = 64),

    CONSTRAINT registrations_checkin_requires_confirmation
        CHECK (NOT checked_in OR status = 'CONFIRMED')
);

CREATE UNIQUE INDEX registrations_one_active_email_per_event
    ON registrations (event_id, email)
    WHERE status IN ('CONFIRMED', 'WAITLISTED');

CREATE INDEX registrations_event_status_order
    ON registrations (event_id, status, id);

COMMIT;
